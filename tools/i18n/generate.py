"""
Builds App/Localization/<lang>.lproj/{Localizable,Core}.strings from tools/i18n/ui.tsv and
tools/i18n/core.tsv, after checking that every string used in the code (tools/i18n/extract.py)
is translated into every language and that the placeholders match.

usage: tools/i18n/generate.py [--check]
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import extract  # noqa: E402

LANGS = ['tr', 'de', 'fr', 'es', 'it', 'fi', 'ru', 'ja', 'ko', 'zh-Hans']
OUT = os.path.join(ROOT, 'App', 'Localization')


def load(name):
    table = {}
    with open(os.path.join(HERE, name), encoding='utf-8') as f:
        for n, line in enumerate(f, 1):
            line = line.rstrip('\n')
            if not line.strip() or line.startswith('#'):
                continue
            cols = [c.strip() for c in line.split(' ‖ ')]
            if len(cols) != len(LANGS) + 1:
                raise SystemExit('%s:%d: expected %d columns, got %d' % (name, n, len(LANGS) + 1, len(cols)))
            table[cols[0]] = dict(zip(LANGS, cols[1:]))
    return table


def placeholders(s):
    return sorted(re.findall(r'%lld|%@|\{\d\}', s))


def escape(s):
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')


def main():
    check_only = '--check' in sys.argv
    ui, core = load('ui.tsv'), load('core.tsv')
    problems = []

    sets = {'Localizable': (extract.ui_keys(), ui), 'Core': (extract.core_keys(), core)}

    for table, (keys, trans) in sets.items():
        for k in keys:
            if k not in trans:
                problems.append('%s: missing translation row for %r' % (table, k))
                continue
            for lang in LANGS:
                t = trans[k][lang]
                if not t:
                    problems.append('%s/%s: empty translation for %r' % (table, lang, k))
                elif placeholders(t) != placeholders(k):
                    problems.append('%s/%s: placeholders differ in %r -> %r' % (table, lang, k, t))
        unused = set(trans) - set(keys)
        for k in sorted(unused):
            problems.append('%s: unused row %r' % (table, k))

    if problems:
        print('\n'.join(problems))
        raise SystemExit(1)

    if check_only:
        print('ok: %d UI and %d core strings, %d languages' % (len(sets['Localizable'][0]), len(sets['Core'][0]), len(LANGS)))
        return

    def write(lang, table, keys, value):
        d = os.path.join(OUT, lang + '.lproj')
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, table + '.strings'), 'w', encoding='utf-8') as f:
            f.write('/* Generated by tools/i18n/generate.py - edit tools/i18n/*.tsv instead. */\n\n')
            for k in keys:
                f.write('"%s" = "%s";\n' % (escape(k), escape(value(k))))

    for table, (keys, trans) in sets.items():
        write('en', table, keys, lambda k: k)
        for lang in LANGS:
            write(lang, table, keys, lambda k, lang=lang: trans[k][lang])

    print('wrote %s for en + %s' % (OUT, ', '.join(LANGS)))


if __name__ == '__main__':
    main()
